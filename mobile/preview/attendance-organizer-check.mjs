// Drives actual React Native components through RN-web; not a device test.
import { chromium } from 'playwright-core';
import os from 'node:os';
import { createServer } from 'vite';
// This sandbox cannot enumerate network interfaces; loopback remains available.
os.networkInterfaces = () => ({});
const server = await createServer({ configFile: 'preview/vite.config.ts', server: { host: '127.0.0.1', port: 5182, strictPort: true } });
await server.listen();
import fs from 'node:fs/promises';
import path from 'node:path';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/tmp/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--no-zygote', '--single-process'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.addInitScript(() => localStorage.setItem('orbit-profile-v1', JSON.stringify({ display_name: 'ORBIT', year: 'final' })));
const page = await context.newPage();
const crashes = [];
page.on('pageerror', error => crashes.push(error.message));
const by = label => page.getByLabel(label, { exact: true }).last();
const tap = async label => { await by(label).click(); await page.waitForTimeout(180); };
const fill = async (label, value) => by(label).fill(value);
const shotDir = path.resolve('../screenshots/attendance-organizer');
await fs.mkdir(shotDir, { recursive: true });
try {
  await page.goto('http://127.0.0.1:5182/?screen=progress', { waitUntil: 'networkidle' });
  await tap('Attendance');
  await tap('Open timetable and organizer');
  await tap('Add weekly class');
  await fill('Title', 'General Medicine');
  await fill('Room or location', 'Ward 3');
  await tap('Save item');
  await page.getByText('General Medicine', { exact: true }).last().waitFor();
  await page.screenshot({ path: path.join(shotDir, 'week.png') });
  await tap('Add weekly class');
  await fill('Title', 'Overlapping class');
  await tap('Save item');
  await page.getByText('This overlaps another class. Check the times.').waitFor();
  await tap('Cancel edit');
  await tap('Organizer Projects');
  await tap('Add project');
  await fill('Title', 'Medicine case presentation');
  await tap('Save item');
  await tap('Organizer Tasks');
  await tap('Add task');
  await fill('Title', 'Write case history');
  await tap('Medicine case presentation');
  await tap('Save item');
  await tap('Complete task Write case history');
  await tap('Organizer Projects');
  await page.getByText('100% complete', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(shotDir, 'projects.png') });
  await tap('Organizer Notes');
  await tap('Add quick note');
  await fill('Title', 'Tomorrow on the ward');
  await fill('Quick note', 'Bring the case sheet and stethoscope.');
  await tap('Save item');
  await page.screenshot({ path: path.join(shotDir, 'notes.png') });
  await tap('Edit Tomorrow on the ward');
  await fill('Quick note', 'Bring case sheet, stethoscope and logbook.');
  await tap('Save item');
  await page.reload({ waitUntil: 'networkidle' });
  await tap('Attendance');
  await tap('Open timetable and organizer');
  await tap('Organizer Notes');
  await page.getByText('Bring case sheet, stethoscope and logbook.', { exact: true }).waitFor();
  await tap('Delete Tomorrow on the ward');
  await tap('Keep item');
  await page.getByText('Bring case sheet, stethoscope and logbook.', { exact: true }).waitFor();
  await tap('Delete Tomorrow on the ward');
  await tap('Confirm delete');
  await tap('Organizer Tasks');
  await page.getByLabel('Reopen task Write case history', { exact: true }).waitFor();
  await tap('Organizer Week');
  await page.evaluate(() => { window.__orbitPickImage = true; });
  await tap('Attach timetable image');
  await by('View timetable image').waitFor();
  await tap('Remove timetable image');
  await tap('Organizer Projects');
  await tap('Delete Medicine case presentation');
  await tap('Confirm delete');
  await tap('Organizer Tasks');
  await by('Reopen task Write case history').waitFor(); // project deletion preserves task
  await tap('Organizer Break');
  await page.screenshot({ path: path.join(shotDir, 'break.png') });
  await tap('Recall card 1');
  await tap('Recall card 2');
  await tap('Restart recall break');
  for (const width of [360, 412]) {
    await page.setViewportSize({ width, height: 844 });
    await page.screenshot({ path: path.join(shotDir, `break-${width}.png`) });
    const overflow = await page.evaluate(() => [...document.querySelectorAll('[aria-label^="Recall card"], [aria-label^="Organizer "], [aria-label="Restart recall break"]')].some(el => { const r = el.getBoundingClientRect(); return r.width > 0 && (r.left < -1 || r.right > window.innerWidth + 1); }));
    if (overflow) throw new Error(`Horizontal overflow at ${width}px`);
  }
  if (crashes.length) throw new Error(crashes.join('\n'));
  console.log('OK organizer UI: create/edit/reload/delete, overlap validation, project-linked tasks, completion, image picker shim, break controls and 360/390/412px layouts');
} finally { await browser.close(); await server.close(); }

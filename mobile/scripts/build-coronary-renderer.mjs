import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../..', import.meta.url));
const require = createRequire(resolve(root, 'mobile/package.json'));
const { build } = require('esbuild');
const input = await readFile(
  resolve(root, 'mobile/coronary-renderer/assets/heart.glb'),
);
const hash = createHash('sha256').update(input).digest('hex');
if (hash !== 'b80a727d022a4ab07ccfcf15caccc228eaccb6d69ec0e72923324946ac35a946')
  throw Error('Unreviewed heart asset');
const payloadPath = resolve(
  root,
  'mobile/coronary-renderer/model-payload.json',
);
await writeFile(
  payloadPath,
  JSON.stringify({ data: gzipSync(input, { level: 9 }).toString('base64') }),
);
const result = await build({
  entryPoints: [resolve(root, 'mobile/coronary-renderer/scene.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  write: false,
  target: 'es2020',
  legalComments: 'inline',
});
const code = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta name="orbit-coronary-renderer" content="webgl"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><style>html,body{margin:0;height:100%;overflow:hidden;background:#11111b;font-family:Arial,sans-serif}canvas{display:block;width:100%;height:100%;touch-action:none}#status{position:absolute;inset:0;display:flex;align-items:center;justify-content:center;padding:20px;color:#e6d9ef;background:#11111b;font-size:13px;text-align:center}#badge{position:absolute;left:12px;top:10px;pointer-events:none;color:#eec1fa;font-size:11px;text-shadow:0 1px 4px #000}#credit{position:absolute;bottom:5px;left:0;width:100%;pointer-events:none;text-align:center;color:#aaa0ba;font-size:9px}</style></head><body><canvas aria-label="Real-time 3D coronary meshes"></canvas><div id="status">Loading real 3D heart…</div><div id="badge"></div><div id="credit">BodyParts3D / DBCLS · CC BY 4.0 · reference anatomy</div><script>${code}</script></body></html>`;
await writeFile(
  resolve(root, 'mobile/src/generated/coronarySceneHtml.ts'),
  '// Generated by mobile/scripts/build-coronary-renderer.mjs. Do not edit.\nexport const CORONARY_SCENE_HTML = ' +
    JSON.stringify(html) +
    ';\n',
);
console.log(
  `Real WebGL renderer: ${Buffer.byteLength(html)} bytes, model ${
    input.length
  } bytes; SHA256 ${hash}`,
);

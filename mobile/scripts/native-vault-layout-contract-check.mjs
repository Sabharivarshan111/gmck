import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const studio = readFileSync(join(here, '../src/components/NativeClinicalStudio.tsx'),'utf8');
const screen = readFileSync(join(here, '../src/screens/SimulatorScreen.tsx'),'utf8');
const web = readFileSync(join(here,'../../src/simulator/controls/SimulatorStudio.css'),'utf8');
assert.match(web,/font-size:clamp\(30px,7vw,44px\)/,'Vercel heading typography reference changed');
assert.match(studio,/Math\.max\(30, Math\.min\(44, width \* 0\.07\)\)/,'Android heading must match 30px/7vw/44px responsive web clamp');
assert.match(studio,/headingSize \* 1\.12/,'Android heading must match website line-height');
assert.match(web,/@media\(max-width:340px\)/);
assert.match(web,/@media\(min-width:640px\)/);
assert.match(studio,/width <= 340 \? 1 : width >= 640 \? 3 : 2/,'Native grid responsive breakpoints changed');
assert.match(studio,/bodyWidth - 12 \* \(columns - 1\)/,'card widths must respect CSS grid gap');
assert.ok(studio.includes('onScenarioChange(s.id)'), 'Native case selector must update parent');
assert.ok(screen.includes('scenarioId={studioScenarioId} onScenarioChange={setStudioScenarioId}'),'case selection not retained across screen navigation');
assert.ok(screen.includes("setNativeMode({ kind: 'monitor', scenarioId: studioScenarioId })"),'monitor must use selected clinical findings');
assert.ok(screen.includes('setStudioScenarioId(destination.id)'), 'case selection should persist on return like web');
console.log('PASS: native studio grid, heading and clinical scenario persistence follow canonical Vercel.');
console.log('NOT pixel parity: Android real-device screenshots must also be compared.');

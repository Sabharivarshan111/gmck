import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { stripTypeScriptTypes } from 'node:module';
const root = path.resolve(import.meta.dirname, '../..');
// Works without npm install; load the exact reviewed arrays, not a synthetic bank.
const files = fs.readdirSync(path.join(root, 'src/data/universityPapers')).filter(file => /^reviewed(?:Questions|Batch\d+)\.ts$/.test(file));
const rows = files.flatMap(file => {
  const source = fs.readFileSync(path.join(root, 'src/data/universityPapers', file), 'utf8');
  const match = /=\s*(\[)/.exec(source);
  const start = match ? match.index + match[0].indexOf('[') : -1;
  if (start < 0) return [];
  try { return JSON.parse(source.slice(start, source.lastIndexOf(']') + 1)); } catch { return []; }
});
assert.equal(rows.length, 15733);
const byId = new Map(rows.map(row => [row.id, row]));
const sourceFor = question => byId.get(question.match(/^PYQ\[([^\]]+)\]/)?.[1]);
let code = fs.readFileSync(path.join(root, 'src/data/universityPapers/presentation.ts'), 'utf8').replace(/^import .*\n/gm, '').replace(/export /g, '');
code = stripTypeScriptTypes(code) + '\nglobalThis.helpers = { repetitionKey, indexExamAppearances, collectedRecordedExamCount, partitionUniversityQuestions };';
const context = { REVIEWED_UNIVERSITY_QUESTIONS: rows, collectedQuestionSource: sourceFor };
vm.runInNewContext(code, context);
const h = context.helpers;
const raw = row => `PYQ[${row.id}] ${row.question}`;
const tabs = h.partitionUniversityQuestions(rows.filter(row => row.kind === 'essay').map(raw), rows.filter(row => row.kind === 'short-notes').map(raw));
assert.equal(tabs.mcq.length, 2768);
assert.equal(Object.values(tabs).flat().length, rows.length);
assert.equal(new Set(Object.values(tabs).flat()).size, rows.length);
assert.ok(tabs.mcq.every(question => sourceFor(question).questionFormat === 'mcq'));
assert.ok(tabs['short-notes'].every(question => sourceFor(question).questionFormat !== 'mcq'));
const base = { ...rows[0], question: 'Glucose 0.5 mg/dl', examRefs: ['Jan 2020 · Code 1'] };
const repeat = { ...base, id: 'repeat', examRefs: ['Jan 2021 · Code 1'] };
const index = h.indexExamAppearances([base, { ...base, id: 'same-exam' }, repeat]);
assert.equal(index.get(h.repetitionKey(base)).size, 2);
assert.notEqual(h.repetitionKey(base), h.repetitionKey({ ...base, university: 'wbuhs' }));
assert.notEqual(h.repetitionKey(base), h.repetitionKey({ ...base, question: 'Glucose 5 mg/dl' }));
const mcq = rows.find(row => row.questionFormat === 'mcq');
assert.notEqual(h.repetitionKey(mcq), h.repetitionKey({ ...mcq, options: mcq.options.map((option, i) => i ? option : { ...option, text: 'Changed choice' }) }));
assert.equal(h.partitionUniversityQuestions(['Describe (a) nerve (b) muscle'], []).mcq.length, 0);
assert.ok(rows.some(row => h.collectedRecordedExamCount(raw(row)) >= 2));
console.log(`PASS: ${rows.length} identities preserved; ${tabs.mcq.length} original MCQs partitioned; repeats scoped by university, wording, choices and exam.`);

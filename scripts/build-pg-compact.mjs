#!/usr/bin/env node
/** Build publisher-declared MIT practice data; never invent years or answer reviews. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const input=path.join(root,'mobile/src/lib/pgPacks');
const quarantine=JSON.parse(fs.readFileSync(path.join(root,'docs/PG_CORPUS_QUARANTINE_20261011.json'),'utf8'));
const excluded=new Set(quarantine.rows.map(q=>q.id));
const groups=new Map();let inventory=0;let explanations=0;let omitted=0;
const files=fs.readdirSync(input).filter(n=>/^(general_medical|neet_pg)_undated_\d+\.ts$/.test(n)).sort();
for(const name of files){
 const text=fs.readFileSync(path.join(input,name),'utf8');
 const array=label=>JSON.parse(text.match(new RegExp('const '+label+'[^=]*=\\s*(\\[.*?\\]);','s'))?.[1]??'null');
 const subjects=array('SUBJECTS'),topics=array('TOPICS'),rows=array('ROWS');
 if(!Array.isArray(rows))throw Error('Unsupported source '+name);
 for(const r of rows){
  inventory++;
  if(excluded.has(r[0])){omitted++;continue;}
  if(!Number.isInteger(r[6])||r[6]<0||r[6]>3)throw Error('Invalid answer index');
  const subject=subjects[r[8]],chapter=topics[r[9]]||'Unclassified — chapter review needed';
  if(!groups.has(subject))groups.set(subject,[]);
  groups.get(subject).push({row:r,chapter});
  if(r[7].trim())explanations++;
 }
}
if(inventory!==quarantine.total_rows||omitted!==quarantine.quarantined_total)throw Error('Inventory/quarantine mismatch');
const publicDir=path.join(root,'public/pg');const nativeDir=path.join(root,'mobile/android/app/src/main/assets/pg');
fs.mkdirSync(publicDir,{recursive:true});fs.mkdirSync(nativeDir,{recursive:true});
for(const directory of [publicDir,nativeDir])for(const name of fs.readdirSync(directory)){
 if(/^(?:s\d{2}(?:-[0-9a-f]{12})?\.zst|manifest\.json|size\.json|LICENSE\.txt|NOTICE\.txt)$/.test(name))fs.unlinkSync(path.join(directory,name));
 else throw Error('Unexpected file in generated PG asset directory: '+name);
}
const license=fs.readFileSync(path.join(root,'docs/licenses/MedMCQA-MIT.txt'),'utf8')+'\n\nBrowser decoder fzstd:\n'+fs.readFileSync(path.join(root,'docs/licenses/fzstd-MIT.txt'),'utf8');
const notice='MedMCQA practice dataset. Publisher-declared MIT licence; see LICENSE.txt. Modified by ORBIT: structural exclusions, compression and chapter indexing. Supplied answers and source chapter labels are not independently medically reviewed. No verified exam-year attribution. Dataset: https://github.com/medmcqa/medmcqa ; licence clarification: https://github.com/medmcqa/medmcqa/issues/2#issuecomment-1329300257\n';
for(const directory of [publicDir,nativeDir]){
 fs.writeFileSync(path.join(directory,'LICENSE.txt'),license);fs.writeFileSync(path.join(directory,'NOTICE.txt'),notice);
}
const packs=[];let binaryBytes=0;
for(const [subject,items] of [...groups].sort(([a],[b])=>a.localeCompare(b))){
 const id='s'+String(packs.length).padStart(2,'0');
 const chapters=[...new Set(items.map(x=>x.chapter))].sort();const chapterIndex=new Map(chapters.map((c,i)=>[c,i]));
 const rows=items.map(({row:r,chapter})=>[r[1],r[2],r[3],r[4],r[5],r[6],r[7],chapterIndex.get(chapter)]);
 const bytes=Buffer.from(JSON.stringify({subject,chapters,rows}));
 const packed=zlib.zstdCompressSync(bytes,{params:{[zlib.constants.ZSTD_c_compressionLevel]:19}});
 if(!zlib.zstdDecompressSync(packed).equals(bytes))throw Error('Lossless round trip failed');
 const sha256=crypto.createHash('sha256').update(packed).digest('hex');
 for(const directory of [publicDir,nativeDir])fs.writeFileSync(path.join(directory,id+'-'+sha256.slice(0,12)+'.zst'),packed);
 binaryBytes+=packed.length;
 packs.push({id,subject,count:rows.length,bytes:packed.length,rawBytes:bytes.length,sha256,chapters:chapters.map((name,i)=>({name,count:rows.filter(r=>r[7]===i).length}))});
}
const manifest={schema:1,inventory,total:inventory-omitted,quarantined:omitted,explanations,missingExplanations:inventory-omitted-explanations,packs};
const manifestText=JSON.stringify(manifest);
for(const directory of [publicDir,nativeDir])fs.writeFileSync(path.join(directory,'manifest.json'),manifestText);
const coreBytes=binaryBytes+Buffer.byteLength(manifestText)+Buffer.byteLength(license)+Buffer.byteLength(notice);
const sizeText=bytes=>JSON.stringify({completeBytes:bytes,binaryBytes,records:manifest.total,codec:'zstd',sourceAnswers:true,medicallyVerified:false});
let completeBytes=coreBytes;for(let i=0;i<3;i++)completeBytes=coreBytes+Buffer.byteLength(sizeText(completeBytes));
if(completeBytes>10000000)throw Error('PG data exceeds 10 MB: '+completeBytes);
const generatedDir=path.join(root,'mobile/src/lib/pgCompact');fs.mkdirSync(generatedDir,{recursive:true});
fs.writeFileSync(path.join(generatedDir,'manifest.ts'),'// Generated by scripts/build-pg-compact.mjs. Dataset labels are not verified taxonomy.\nexport const PG_COMPACT = '+manifestText+';\nexport const PG_COMPACT_BYTES = '+completeBytes+';\n');
for(const directory of [publicDir,nativeDir])fs.writeFileSync(path.join(directory,'size.json'),sizeText(completeBytes));
console.log(JSON.stringify({inventory,available:manifest.total,quarantined:omitted,packs:packs.length,completeBytes,MB:completeBytes/1000000,explanations,missingExplanations:manifest.missingExplanations}));

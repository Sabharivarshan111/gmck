#!/usr/bin/env python3
"""Recompute audit and runtime gate atomically from actual assets; --check detects drift."""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
PATH=Path(__file__).with_name('audit-pg-corpus.py')
spec=importlib.util.spec_from_file_location('pg_corpus_audit',PATH)
audit=importlib.util.module_from_spec(spec);spec.loader.exec_module(audit)

def render(quarantine):
    ids=json.dumps([r['id'] for r in quarantine['rows']],ensure_ascii=False,indent=2)
    counts=json.dumps(quarantine['eligible_pack_counts'],sort_keys=True,indent=2)
    return ('/** Generated by scripts/generate-pg-quarantine.py; never hand-edit.\n'
            ' * Structural eligibility is not independent medical verification. */\n'
            f'export const PG_CORPUS_AUDIT_DATE = {json.dumps(audit.DATE)};\n'
            f'export const PG_CORPUS_ASSET_FINGERPRINT = {json.dumps(quarantine["asset_fingerprint"])};\n'
            f'export const PG_QUARANTINED_TOTAL = {quarantine["quarantined_total"]};\n'
            f'export const PG_STRUCTURALLY_ELIGIBLE_TOTAL = {quarantine["structurally_eligible_total"]};\n'
            f'export const PG_QUARANTINED_IDS: ReadonlySet<string> = new Set({ids});\n'
            f'export const PG_ELIGIBLE_PACK_COUNTS: Readonly<Record<string, number>> = {counts};\n')

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    audit.self_test()
    report, quarantine=audit.audit()
    audit.write_json(audit.ROOT/'docs/PG_CORPUS_AUDIT_20261011.json',report,args.check)
    audit.write_json(audit.ROOT/'docs/PG_CORPUS_QUARANTINE_20261011.json',quarantine,args.check)
    path=audit.ROOT/'mobile/src/lib/pgQuarantine.ts';content=render(quarantine)
    if args.check:
        if not path.exists() or path.read_text()!=content: raise SystemExit('Stale pgQuarantine.ts: regenerate from current assets')
    else: path.write_text(content)
    print(f'PG quarantine {"checked" if args.check else "generated"}: {quarantine["quarantined_total"]} withheld; {quarantine["structurally_eligible_total"]} structurally eligible')
if __name__=='__main__':main()

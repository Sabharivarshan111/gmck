import assert from 'node:assert/strict';
import { planCoverage, defaultNeetPlan, emptyNeetStudy, studyDay, addStudyDays, validStudyDate, dailyQuestionOffset, recordNeetAttempt, planSession, parseNeetStudy } from '../mobile/src/lib/neetPgPlan.ts';
assert.equal(addStudyDays('2028-02-28', 1), '2028-02-29');
assert.equal(addStudyDays('2026-12-31', 1), '2027-01-01');
assert.equal(validStudyDate('2026-02-31'), false);
assert.equal(studyDay(new Date(2026,9,20,23,59)), '2026-10-20');
assert.equal(dailyQuestionOffset('2026-10-20', 2078), dailyQuestionOffset('2026-10-20', 2078));
assert.notEqual(dailyQuestionOffset('2026-10-20', 2078), dailyQuestionOffset('2026-10-21', 2078));
let attempt = recordNeetAttempt(undefined, 2, 2, '2026-10-20');
assert.equal(attempt.due, '2026-10-21');
attempt = recordNeetAttempt(attempt, 2, 2, '2026-10-20');
assert.equal(attempt.streak, 1, 'toggling reveal cannot grow a streak');
attempt = recordNeetAttempt(attempt, 2, 2, '2026-10-21');
assert.equal(attempt.due, '2026-10-24');
assert.equal(recordNeetAttempt(attempt, 0, 2, '2026-10-24').streak, 0);
assert.equal(recordNeetAttempt(undefined, undefined, 2, '2026-10-20').correct, null);
assert.equal(recordNeetAttempt(undefined, 2, null, '2026-10-20').correct, null);
const state = emptyNeetStudy(); state.plan = { ...defaultNeetPlan(), minutes: 10, subjects: ['medicine'] };
state.attempts.old = recordNeetAttempt(undefined, 0, 2, '2026-10-19');
const records = [{id:'old',subject:'anatomy'}, ...Array.from({length:10}, (_,i)=>({id:'q'+i,subject:i>4?'medicine':'anatomy'}))];
const session = planSession(records, state, '2026-10-20');
assert.equal(session.ids.length,5); assert.equal(session.ids[0],'old'); assert.equal(session.ids[1],'q5');
assert.equal(new Set(session.ids).size,5);
state.session = session;
assert.deepEqual(parseNeetStudy(JSON.stringify(state)),state);
assert.deepEqual(parseNeetStudy('{bad'),emptyNeetStudy());
assert.equal(parseNeetStudy('{"plan":{"days":[]},"attempts":{"q":null}}').plan,null);
assert.equal(planSession([],state,'2026-10-20').ids.length,0);
console.log('NEET planner: dates, due reviews, capacity, priorities, answer scoring, stable daily selection and persistence passed');

assert.deepEqual(planCoverage({...defaultNeetPlan(),examDate:'2026-10-22',days:[2,4],minutes:10},100,'2026-10-20'),{sessions:2,neededPerSession:50,budget:5});
